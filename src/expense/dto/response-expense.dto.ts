import { ApiProperty, ApiPropertyOptional } from '@nestjs/swagger';
import { Currency } from '@prisma/client';
import { Exclude } from 'class-transformer';

export class ExpenseResponseDto {
  @ApiProperty({ example: 1, description: 'Unique ID of the expense generated by the database' })
  id!: number;

  @Exclude()
  id_participant!: number;

  @ApiProperty({ example: 1, description: 'ID of the trip associated with this expense' })
  id_trip!: number;

  @Exclude()
  amount!: number;

  @ApiProperty({ example: 'EUR', description: 'Currency of the expense' })
  currency!: Currency;

  @ApiPropertyOptional({ example: '2026-08-27', description: 'Date of the expense' })
  date!: Date;
}